//! What the DDL declares of a column, a key and a sequence, as a write meets it: each DEFAULT filled,
//! an identity's and a serial's values handed out by its sequence, whose advance lies in the file and
//! is never given back; a stored generated column computed at the write and a virtual one at the
//! read; each CHECK and UNIQUE refusing what PostgreSQL refuses; and an INSERT … SELECT taking its
//! values by PostgreSQL's assignment casts.

#![cfg(feature = "standalone")]

mod weather;

use arrow::array::{Array, RecordBatch, TimestampMicrosecondArray};
use warren_snail::catalog::Catalog;
use warren_snail::read::Snail;
use weather::{tmp, write};

fn made(name: &str, ddl: &str) -> std::path::PathBuf {
    let path = tmp(&format!("{name}.snail"));
    write(&path, &Catalog::parse(ddl).unwrap(), &[]).unwrap();
    path
}

fn run(w: &mut Snail, sql: &str) {
    w.execute(sql).unwrap_or_else(|e| panic!("{sql}: {e}"));
}

fn refused(w: &mut Snail, sql: &str, why: &str) {
    let e = w
        .execute(sql)
        .err()
        .unwrap_or_else(|| panic!("{sql} was taken"))
        .to_string();
    assert!(e.contains(why), "{sql}: {e}");
}

/// An answer's rows, each cell as arrow writes it, NULL as none, sorted.
fn rows(s: &mut Snail, sql: &str) -> Vec<Vec<Option<String>>> {
    let (b, _): (RecordBatch, _) = s.ask(sql, None).unwrap_or_else(|e| panic!("{sql}: {e}"));
    let mut out: Vec<Vec<Option<String>>> = (0..b.num_rows())
        .map(|r| {
            b.columns()
                .iter()
                .map(|a| {
                    (!a.is_null(r))
                        .then(|| arrow::util::display::array_value_to_string(a, r).unwrap())
                })
                .collect()
        })
        .collect();
    out.sort();
    out
}

fn row(cells: &[&str]) -> Vec<Option<String>> {
    cells
        .iter()
        .map(|c| (*c != "NULL").then(|| c.to_string()))
        .collect()
}

#[test]
fn defaults_identities_and_serials_fill_a_row_as_postgresql_fills_it() {
    let path = made(
        "defaults",
        "CREATE SEQUENCE s.no START WITH 100 INCREMENT BY 10;
         CREATE TABLE s.t (id bigint GENERATED ALWAYS AS IDENTITY, n bigint NOT NULL DEFAULT nextval('s.no'),
             q integer NOT NULL DEFAULT 1, label text DEFAULT 'none', small smallint DEFAULT -1,
             m numeric(6,2) DEFAULT 1 + 1, at timestamptz DEFAULT now(), PRIMARY KEY (id));
         CREATE TABLE s.u (id serial, b integer GENERATED BY DEFAULT AS IDENTITY (START WITH 5), PRIMARY KEY (id));",
    );
    let mut w = Snail::open_writing(&path).unwrap();
    run(&mut w, "INSERT INTO s.t (q) VALUES (7), (DEFAULT)");
    run(&mut w, "INSERT INTO s.t (label) VALUES (NULL)");
    run(
        &mut w,
        "INSERT INTO s.u (b) VALUES (DEFAULT), (50), (DEFAULT)",
    );
    refused(
        &mut w,
        "INSERT INTO s.t (id, q) VALUES (9, 1)",
        "cannot insert a non-DEFAULT value into column \"id\"",
    );
    refused(
        &mut w,
        "UPDATE s.t SET id = 9 WHERE id = 1",
        "can only be updated to DEFAULT",
    );
    drop(w);
    let mut s = Snail::open(&path).unwrap();
    assert_eq!(
        rows(&mut s, "SELECT id, n, q, label, small, m FROM s.t"),
        [
            row(&["1", "100", "7", "none", "-1", "2.00"]),
            row(&["2", "110", "1", "none", "-1", "2.00"]),
            row(&["3", "120", "1", "NULL", "-1", "2.00"]),
        ]
    );
    // The first two rows were inserted by one statement, so they read one clock.
    let (b, _) = s.ask("SELECT id, at FROM s.t ORDER BY id", None).unwrap();
    let at: Vec<i64> = b
        .column(1)
        .as_any()
        .downcast_ref::<TimestampMicrosecondArray>()
        .unwrap()
        .values()
        .to_vec();
    assert_eq!(at[0], at[1]);
    assert!(at[2] >= at[1]);
    assert_eq!(
        rows(&mut s, "SELECT id, b FROM s.u"),
        [row(&["1", "5"]), row(&["2", "50"]), row(&["3", "6"])]
    );
}

#[test]
fn a_sequence_s_advance_lies_in_the_file_and_is_never_given_back() {
    let path = made(
        "advance",
        "CREATE TABLE s.t (id integer GENERATED BY DEFAULT AS IDENTITY, v text, PRIMARY KEY (id));
         CREATE SEQUENCE s.c MAXVALUE 2 CYCLE;
         CREATE SEQUENCE s.e MAXVALUE 2;
         CREATE TABLE s.k (id bigint NOT NULL, c bigint DEFAULT nextval('s.c'), e bigint DEFAULT nextval('s.e'), PRIMARY KEY (id));",
    );
    let mut w = Snail::open_writing(&path).unwrap();
    run(&mut w, "INSERT INTO s.t (v) VALUES ('a')");
    run(&mut w, "BEGIN");
    run(&mut w, "INSERT INTO s.t (v) VALUES ('b'), ('c')");
    run(&mut w, "ROLLBACK");
    run(&mut w, "INSERT INTO s.t (v) VALUES ('d')");
    drop(w);
    let mut s = Snail::open(&path).unwrap();
    // The rolled-back transaction's values 2 and 3 are not handed out again.
    assert_eq!(
        rows(&mut s, "SELECT id, v FROM s.t"),
        [row(&["1", "a"]), row(&["4", "d"])]
    );
    let state = s.sequences().unwrap();
    assert!(
        state.contains(&("s.t_id_seq".to_string(), 4, true)),
        "{state:?}"
    );
    assert!(state.contains(&("s.c".to_string(), 1, false)), "{state:?}");
    drop(s);
    // A writer opened afresh goes on where the file stands.
    let mut w = Snail::open_writing(&path).unwrap();
    run(&mut w, "INSERT INTO s.t (v) VALUES ('e')");
    run(
        &mut w,
        "INSERT INTO s.k (id, e) VALUES (1, 0), (2, 0), (3, 0)",
    );
    refused(
        &mut w,
        "INSERT INTO s.k (id, c) VALUES (4, 0), (5, 0), (6, 0)",
        "nextval: reached maximum value of sequence \"e\" (2)",
    );
    drop(w);
    let mut s = Snail::open(&path).unwrap();
    assert!(rows(&mut s, "SELECT id, v FROM s.t").contains(&row(&["5", "e"])));
    // A sequence that cycles starts again at its MINVALUE.
    assert_eq!(
        rows(&mut s, "SELECT id, c FROM s.k"),
        [row(&["1", "1"]), row(&["2", "2"]), row(&["3", "1"])]
    );
}

#[test]
fn two_writers_never_take_one_value_and_each_holds_its_cache() {
    let path = made(
        "cache",
        "CREATE SEQUENCE s.n CACHE 3;
         CREATE TABLE s.t (id bigint NOT NULL DEFAULT nextval('s.n'), who text, PRIMARY KEY (id));",
    );
    let mut a = Snail::open_writing(&path).unwrap();
    let mut b = Snail::open_writing(&path).unwrap();
    run(&mut a, "INSERT INTO s.t (who) VALUES ('a')");
    run(&mut b, "INSERT INTO s.t (who) VALUES ('b')");
    run(&mut a, "INSERT INTO s.t (who) VALUES ('a')");
    run(&mut b, "INSERT INTO s.t (who) VALUES ('b'), ('b'), ('b')");
    drop((a, b));
    let mut s = Snail::open(&path).unwrap();
    // a holds 1 to 3 and b 4 to 6, as PostgreSQL's sessions each cache CACHE values; b's third value
    // takes a run of its own, 7 to 9.
    assert_eq!(
        rows(&mut s, "SELECT id, who FROM s.t"),
        [
            row(&["1", "a"]),
            row(&["2", "a"]),
            row(&["4", "b"]),
            row(&["5", "b"]),
            row(&["6", "b"]),
            row(&["7", "b"])
        ]
    );
    assert_eq!(s.sequences().unwrap(), [("s.n".to_string(), 9, true)]);
}

#[test]
fn a_generated_column_is_computed_at_the_write_where_stored_and_at_the_read_where_virtual() {
    let path = made(
        "generated",
        "CREATE TABLE s.t (id integer NOT NULL, q integer NOT NULL, p numeric(6,2) NOT NULL,
             gross numeric(12,2) GENERATED ALWAYS AS (q * p) STORED,
             next integer GENERATED ALWAYS AS (q + 1) VIRTUAL, PRIMARY KEY (id));",
    );
    let mut w = Snail::open_writing(&path).unwrap();
    run(
        &mut w,
        "INSERT INTO s.t (id, q, p) VALUES (1, 3, 2.50), (2, 2, 1.00)",
    );
    run(&mut w, "UPDATE s.t SET q = 4 WHERE id = 2");
    run(
        &mut w,
        "UPDATE s.t SET gross = DEFAULT, next = DEFAULT WHERE id = 1",
    );
    refused(
        &mut w,
        "INSERT INTO s.t (id, q, p, gross) VALUES (3, 1, 1, 9)",
        "cannot insert a non-DEFAULT value into column \"gross\"",
    );
    refused(
        &mut w,
        "UPDATE s.t SET next = 9 WHERE id = 1",
        "can only be updated to DEFAULT",
    );
    drop(w);
    let mut s = Snail::open(&path).unwrap();
    let want = [row(&["1", "7.50", "4"]), row(&["2", "4.00", "5"])];
    // A scan, as the wrapper asks one, reads the columns the table stores, and names a virtual one.
    let e = s
        .scan("SELECT id, next FROM s.t", None)
        .err()
        .unwrap()
        .to_string();
    assert!(e.contains("next is a virtual generated column"), "{e}");
    assert_eq!(rows(&mut s, "SELECT id, gross, next FROM s.t"), want);
    assert_eq!(
        rows(
            &mut s,
            "WITH x AS (SELECT id, gross, next FROM s.t) SELECT id, gross, next FROM x"
        ),
        want
    );
    assert_eq!(
        rows(&mut s, "SELECT id FROM s.t WHERE next > 4"),
        [row(&["2"])]
    );
    // A question that reads no virtual column reads the table along its orders, as before.
    let (_, round) = s.ask("SELECT q FROM s.t WHERE id = 1", None).unwrap();
    assert_eq!(round.order, "t_pkey");
    // A virtual column goes out with no values: `out` writes the columns the table stores.
    drop(s);
    let mut s = Snail::open_writing(&path).unwrap();
    let dir = tmp("generated-out");
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    let gone = s.out(&dir).unwrap();
    let file = std::fs::File::open(&gone[0].file).unwrap();
    let r = parquet::arrow::arrow_reader::ParquetRecordBatchReaderBuilder::try_new(file).unwrap();
    let names: Vec<String> = r
        .schema()
        .fields()
        .iter()
        .map(|f| f.name().clone())
        .collect();
    assert_eq!(names, ["id", "q", "p", "gross"]);
}

#[test]
fn checks_refuse_what_postgresql_refuses_and_a_null_passes() {
    let path = made(
        "checks",
        "CREATE TABLE s.t (id integer NOT NULL, q integer CHECK (q > 0), d numeric(4,3),
             CONSTRAINT d_range CHECK (d >= 0 AND d < 1), CONSTRAINT cap CHECK (q < 100) NOT ENFORCED,
             PRIMARY KEY (id));",
    );
    let mut w = Snail::open_writing(&path).unwrap();
    run(
        &mut w,
        "INSERT INTO s.t (id, q, d) VALUES (1, 5, 0.5), (2, NULL, NULL), (3, 500, 0)",
    );
    refused(
        &mut w,
        "INSERT INTO s.t (id, q) VALUES (4, 0)",
        "new row for relation \"t\" violates check constraint \"t_q_check\"",
    );
    refused(
        &mut w,
        "UPDATE s.t SET d = 1 WHERE id = 1",
        "violates check constraint \"d_range\"",
    );
    // A CHECK added valid is checked against the rows held; NOT VALID only against those written
    // after; VALIDATE CONSTRAINT against them all.
    refused(
        &mut w,
        "ALTER TABLE s.t ADD CONSTRAINT small CHECK (q < 50)",
        "check constraint \"small\" of relation \"t\" is violated by some row",
    );
    run(
        &mut w,
        "ALTER TABLE s.t ADD CONSTRAINT small CHECK (q < 50) NOT VALID",
    );
    refused(
        &mut w,
        "INSERT INTO s.t (id, q) VALUES (5, 60)",
        "violates check constraint \"small\"",
    );
    refused(
        &mut w,
        "ALTER TABLE s.t VALIDATE CONSTRAINT small",
        "is violated by some row",
    );
    run(&mut w, "DELETE FROM s.t WHERE id = 3");
    run(&mut w, "ALTER TABLE s.t VALIDATE CONSTRAINT small");
    drop(w);
    let mut s = Snail::open(&path).unwrap();
    assert_eq!(
        rows(&mut s, "SELECT id FROM s.t"),
        [row(&["1"]), row(&["2"])]
    );
    let k = &s.catalog.tables[0].checks;
    assert!(k.iter().find(|k| k.name == "small").unwrap().valid);
}

#[test]
fn a_unique_constraint_refuses_a_second_row_and_takes_its_nulls_as_declared() {
    let path = made(
        "unique",
        "CREATE TABLE s.t (id integer NOT NULL, a integer UNIQUE, b integer UNIQUE NULLS NOT DISTINCT,
             k integer, PRIMARY KEY (id), CONSTRAINT t_k UNIQUE (k) DEFERRABLE);",
    );
    let mut w = Snail::open_writing(&path).unwrap();
    run(
        &mut w,
        "INSERT INTO s.t (id, a, b, k) VALUES (1, NULL, NULL, 1), (2, NULL, 5, 2)",
    );
    refused(
        &mut w,
        "INSERT INTO s.t (id, a, b, k) VALUES (3, NULL, 7, 2)",
        "t_k",
    );
    refused(
        &mut w,
        "INSERT INTO s.t (id, b, k) VALUES (3, NULL, 3)",
        "t_b_key",
    );
    // Any number of NULLs under a UNIQUE whose NULLs are distinct.
    run(
        &mut w,
        "INSERT INTO s.t (id, a, b, k) VALUES (3, NULL, 8, 3)",
    );
    // A key is checked at the statement's end: in one statement, a value moved off and another
    // onto it.
    run(&mut w, "DELETE FROM s.t WHERE id = 3");
    run(&mut w, "INSERT INTO s.t (id, b, k) VALUES (3, 9, 3)");
    refused(&mut w, "UPDATE s.t SET k = 3 WHERE id = 1", "t_k");
    drop(w);
    let mut s = Snail::open(&path).unwrap();
    assert_eq!(
        rows(&mut s, "SELECT id, k FROM s.t"),
        [row(&["1", "1"]), row(&["2", "2"]), row(&["3", "3"])]
    );
}

#[test]
fn an_insert_select_takes_its_values_by_postgresql_s_assignment_casts() {
    let path = made(
        "assign",
        "CREATE TABLE s.src (id bigint NOT NULL, big bigint, m numeric(9,3), f boolean, at timestamptz, PRIMARY KEY (id));
         CREATE TABLE s.dst (id integer NOT NULL, small smallint, m numeric(9,1), t text, v varchar(5), PRIMARY KEY (id));",
    );
    let mut w = Snail::open_writing(&path).unwrap();
    run(
        &mut w,
        "INSERT INTO s.src (id, big, m, f, at) VALUES (1, 7, 2.25, true, '2020-01-02 03:04:05.5+00'), (2, 70000, -2.25, false, '1999-12-31 23:59:59+00')",
    );
    run(
        &mut w,
        "INSERT INTO s.dst (id, small, m, t, v) SELECT s.id, s.id, s.m, s.at, s.f FROM s.src s",
    );
    refused(
        &mut w,
        "INSERT INTO s.dst (id, small) SELECT s.big, s.big FROM s.src s",
        "smallint out of range",
    );
    refused(
        &mut w,
        "INSERT INTO s.dst (id, small) SELECT s.id, s.f FROM s.src s WHERE s.id > 99",
        "column \"small\" is of type smallint but expression is of type boolean",
    );
    drop(w);
    let mut s = Snail::open(&path).unwrap();
    assert_eq!(
        rows(&mut s, "SELECT id, small, m, t, v FROM s.dst"),
        [
            row(&["1", "1", "2.3", "2020-01-02 03:04:05.5+00", "true"]),
            row(&["2", "2", "-2.3", "1999-12-31 23:59:59+00", "false"]),
        ]
    );
}

#[test]
fn a_snail_of_format_eight_refuses_by_name_what_0_1_x_cannot_read() {
    for (ddl, why) in [
        (
            "CREATE TABLE s.t (a integer NOT NULL, b integer DEFAULT 1, PRIMARY KEY (a));",
            "s.t.b has a DEFAULT, a generation or an identity, which a snail of format 8",
        ),
        (
            "CREATE TABLE s.t (a integer NOT NULL CHECK (a > 0), PRIMARY KEY (a));",
            "s.t: the CHECK t_a_check, which a snail of format 8",
        ),
        (
            "CREATE TABLE s.t (a integer NOT NULL, b integer UNIQUE, PRIMARY KEY (a));",
            "s.t: the UNIQUE t_b_key, which a snail of format 8",
        ),
        (
            "CREATE SEQUENCE s.n; CREATE TABLE s.t (a integer NOT NULL, PRIMARY KEY (a));",
            "the sequence s.n, which a snail of format 8",
        ),
    ] {
        let path = tmp("eight-refuses.snail");
        let e = warren_snail::write::write_format_eight(
            &path,
            &Catalog::parse(ddl).unwrap(),
            &[],
            weather::span(),
        )
        .err()
        .unwrap()
        .to_string();
        assert!(e.contains(why) && e.contains("`out`"), "{ddl}: {e}");
    }
    // Declared into a snail of format 8 the same way; and a primary key named by its constraint
    // keeps the name 0.1.x gave its order there.
    let path = tmp("eight-declares.snail");
    warren_snail::write::write_format_eight(
        &path,
        &Catalog::parse("CREATE TABLE s.t (a integer NOT NULL, CONSTRAINT k PRIMARY KEY (a));")
            .unwrap(),
        &[],
        weather::span(),
    )
    .unwrap();
    let mut w = Snail::open_writing(&path).unwrap();
    assert_eq!(w.catalog.tables[0].orders[0].name, "t_pkey");
    refused(
        &mut w,
        "CREATE SEQUENCE s.n",
        "the sequence s.n, which a snail of format 8",
    );
    run(&mut w, "INSERT INTO s.t (a) VALUES (1)");
}

#[test]
fn a_literal_too_long_for_its_column_is_refused_before_a_value_is_drawn() {
    let path = made(
        "literal-first",
        "CREATE TABLE s.t (id integer GENERATED ALWAYS AS IDENTITY, code varchar(3), small smallint, PRIMARY KEY (id));",
    );
    let mut w = Snail::open_writing(&path).unwrap();
    refused(
        &mut w,
        "INSERT INTO s.t (code) VALUES ('four')",
        "value too long for type character varying(3)",
    );
    refused(
        &mut w,
        "INSERT INTO s.t (small) VALUES (70000)",
        "out of range",
    );
    run(&mut w, "INSERT INTO s.t (code) VALUES ('ab  ')");
    drop(w);
    let mut s = Snail::open(&path).unwrap();
    // PostgreSQL refuses a literal as it plans the statement, so the identity drew nothing for it.
    assert_eq!(
        rows(&mut s, "SELECT id, code FROM s.t"),
        [row(&["1", "ab "])]
    );
}

#[test]
fn now_reads_the_transaction_s_clock_and_statement_timestamp_the_statement_s() {
    let path = made(
        "clocks",
        "CREATE TABLE s.t (id integer NOT NULL, now timestamptz DEFAULT now(),
             st timestamptz DEFAULT statement_timestamp(), PRIMARY KEY (id));",
    );
    let mut w = Snail::open_writing(&path).unwrap();
    run(&mut w, "BEGIN");
    run(&mut w, "INSERT INTO s.t (id) VALUES (1)");
    std::thread::sleep(std::time::Duration::from_millis(3));
    run(&mut w, "INSERT INTO s.t (id) VALUES (2)");
    run(&mut w, "COMMIT");
    drop(w);
    let mut s = Snail::open(&path).unwrap();
    let (b, _) = s
        .ask("SELECT id, now, st FROM s.t ORDER BY id", None)
        .unwrap();
    let col = |i: usize| -> Vec<i64> {
        b.column(i)
            .as_any()
            .downcast_ref::<TimestampMicrosecondArray>()
            .unwrap()
            .values()
            .to_vec()
    };
    let (now, st) = (col(1), col(2));
    assert_eq!(now[0], now[1], "now() is the transaction's");
    assert!(
        st[1] > st[0],
        "statement_timestamp() is each statement's: {st:?}"
    );
}

#[test]
fn a_census_counts_the_page_that_holds_the_sequences() {
    // A copy of a snail, a table with an identity declared on it and one row inserted: the root now
    // names where its sequence stands, and every page of the file is named or free, once.
    let path = made(
        "census-sequences",
        "CREATE TABLE s.k (id integer NOT NULL, PRIMARY KEY (id));",
    );
    let copy = tmp("census-sequences-copy.snail");
    std::fs::copy(&path, &copy).unwrap();
    let mut w = Snail::open_writing(&copy).unwrap();
    run(
        &mut w,
        "CREATE TABLE s.t (id integer GENERATED ALWAYS AS IDENTITY, v text, PRIMARY KEY (id))",
    );
    run(&mut w, "INSERT INTO s.t (v) VALUES ('a')");
    drop(w);
    let s = Snail::open(&copy).unwrap();
    assert!(!s.sequences().unwrap().is_empty());
    let census = s
        .census()
        .unwrap_or_else(|e| panic!("the census of a file holding a sequence: {e}"));
    assert!(census.named > 0, "{census:?}");
}
